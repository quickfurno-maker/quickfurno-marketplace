assert.match(cfg,/VOX_STAFF_PORTAL_ENABLED==="staging"/);
assert.match(cfg,/https:\/\/vox\.quickfurno\.in/);
assert.match(request,/allowedOrigin\(request\)/);
assert.match(request,/resetPasswordForEmail/);
assert.match(request,/Object\.keys\(x\)\.length!==1/);
assert.doesNotMatch(request,/console\.log|service_role|adminClient/);
assert.match(callback,/trustedRecoveryHost\(request\)/);
assert.match(callback,/exchangeCodeForSession\(code\)/);
assert.match(callback,/params\.length!==1/);
assert.match(callback,/verifyRecoveryTicket\(init,"init"/);
assert.doesNotMatch(callback,/url\.searchParams\.get\("next"\)|x-forwarded-host/);
assert.match(complete,/allowedOrigin\(request\)/);
assert.match(complete,/store\.delete\(COMPLETE_COOKIE\)/);
assert.match(complete,/verifyRecoveryTicket\(ticket,"complete"/);
assert.match(complete,/auth\.auth\.updateUser/);
assert.match(complete,/auth\.auth\.signOut\(\)/);
assert.match(auth,/-code-verifier"\)\?"lax":"strict"/);
assert.match(pages,/recoveryEnabled\(\)/);
assert.match(read(".env.example"),/VOX_PASSWORD_RECOVERY_ENABLED=disabled/);
console.log("VOX_PASSWORD_RECOVERY_GATES_PASS functional_ticket_positive=2 functional_ticket_negative=10 route_guards=19 default_off=true");

