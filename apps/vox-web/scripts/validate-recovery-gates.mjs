import assert from "node:assert/strict";
import {randomBytes} from "node:crypto";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {issueRecoveryTicket,verifyRecoveryTicket,emailDigest} from "../lib/recoveryTicket.mjs";
const root=resolve(fileURLToPath(new URL("..",import.meta.url)));
const read=(p)=>readFileSync(resolve(root,p),"utf8");
const key=randomBytes(32).toString("base64url");
const wrongKey=randomBytes(32).toString("base64url");
const email=emailDigest("staff@example.org"),other=emailDigest("other@example.org");
const now=Date.now();
const init=issueRecoveryTicket("init",email,key,now);
assert.equal(verifyRecoveryTicket(init,"init",email,key,now),true);
assert.equal(verifyRecoveryTicket(init,"complete",email,key,now),false);
assert.equal(verifyRecoveryTicket(init,"init",other,key,now),false);
assert.equal(verifyRecoveryTicket(init,"init",email,wrongKey,now),false);
assert.equal(verifyRecoveryTicket(init,"init",email,key,now+600001),false);
assert.equal(verifyRecoveryTicket(init,"init",email,key,now-1),false);
assert.equal(verifyRecoveryTicket(init.slice(0,-1)+(init.endsWith("f")?"a":"f"),"init",email,key,now),false);
assert.equal(verifyRecoveryTicket("malformed","init",email,key,now),false);
assert.throws(()=>issueRecoveryTicket("init",email,"bad-key",now));
const done=issueRecoveryTicket("complete","11111111-1111-4111-8111-111111111111",key,now);
assert.equal(verifyRecoveryTicket(done,"complete","11111111-1111-4111-8111-111111111111",key,now),true);
assert.equal(verifyRecoveryTicket(done,"complete","22222222-2222-4222-8222-222222222222",key,now),false);
const cfg=read("lib/recoveryStage.ts");
const request=read("app/api/auth/recovery/request/route.ts");
const callback=read("app/auth/callback/route.ts");
const complete=read("app/api/auth/recovery/complete/route.ts");
const auth=read("lib/auth.ts");
const pages=read("app/password/recover/page.tsx")+read("app/password/reset/page.tsx");
assert.match(cfg,/VOX_PASSWORD_RECOVERY_ENABLED==="staging"/);
assert.match(cfg,/VOX_STAFF_PORTAL_ENABLED==="staging"/);
assert.match(cfg,/https:\/\/vox\.quickfurno\.in/);
assert.match(request,/allowedOrigin\(request\)/);
assert.match(request,/resetPasswordForEmail/);
assert.match(request,/Object\.keys\(x\)\.length!==1/);
assert.doesNotMatch(request,/console\.log|service_role|adminClient/);
assert.match(callback,/trustedRecoveryHost\(request\)/);
assert.match(callback,/exchangeCodeForSession\(code\)/);
assert.match(callback,/params\.length!==1/);
assert.match(callback,/verifyRecoveryTicket\(init,"init"/);
assert.doesNotMatch(callback,/url\.searchParams\.get\("next"\)|x-forwarded-host/);
assert.match(complete,/allowedOrigin\(request\)/);
assert.match(complete,/store\.delete\(COMPLETE_COOKIE\)/);
assert.match(complete,/verifyRecoveryTicket\(ticket,"complete"/);
assert.match(complete,/auth\.auth\.updateUser/);
assert.match(complete,/auth\.auth\.signOut\(\)/);
assert.match(auth,/-code-verifier"\)\?"lax":"strict"/);
assert.match(pages,/recoveryEnabled\(\)/);
assert.match(read(".env.example"),/VOX_PASSWORD_RECOVERY_ENABLED=disabled/);
console.log("VOX_PASSWORD_RECOVERY_GATES_PASS functional_ticket_positive=2 functional_ticket_negative=10 route_guards=19 default_off=true");
