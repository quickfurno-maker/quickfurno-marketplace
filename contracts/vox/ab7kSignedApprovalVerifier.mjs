/** AB7K RC3 reusable Ed25519 signed-approval VERIFIER (not a writer, not an approval).
 *
 * What a `ok:true` result proves: a private key matching a PINNED public key
 * in the approved signer registry signed these exact domain-separated bytes,
 * the bytes are bound to the expected subject/digest/target/Owner/TL, the
 * signature is inside its lifetime, and (when a store is supplied) the nonce
 * was claimed first time.
 *
 * What it does NOT prove, and why `approved`/`canAuthorize` are always false:
 *  - that the signer is a real, currently-enrolled human (enrolment is a
 *    separate governed process; the registry is only as trustworthy as its
 *    out-of-band provisioning);
 *  - server-verified AAL2 for the current Owner/TL session;
 *  - an authorized, atomic, database-side writer that re-checks all of this.
 * A SHA-256 digest is a content binding, NEVER a signature. No digest-only
 * or boolean input is accepted as evidence here.
 *
 * Trusted public keys come from server configuration only; no private key is
 * ever read, accepted or generated by this module. Empty config => DENY.
 */
import {createHash,createPublicKey,verify} from "node:crypto";

export const AB7K_APPROVAL_DOMAIN="qf.vox.ab7k.signed-approval";
export const AB7K_APPROVAL_VERSION="v1";
export const AB7K_APPROVAL_TYPES=Object.freeze(["EOD_OFFICIAL_RELEASE","OPERATOR_COMMAND"]);
export const AB7K_SIGNER_ROLES=Object.freeze(["OWNER","TEAM_LEADER"]);
export const AB7K_SIGNER_REGISTRY_ENV="VOX_AB7K_APPROVAL_SIGNER_REGISTRY_JSON";
export const AB7K_MAX_LIFETIME_MS=15*60*1000;
const MAX_SKEW_MS=30*1000;
const MAX_REGISTRY_ENTRIES=16;

const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
const HEX64=/^[a-f0-9]{64}$/;
const KEY_ID=/^[A-Za-z0-9][A-Za-z0-9._:-]{3,63}$/;
const SIGNATURE=/^[A-Za-z0-9_-]{86}$/;
const PUBLIC_PEM=/^-----BEGIN PUBLIC KEY-----\r?\n[A-Za-z0-9+/=\r\n]+-----END PUBLIC KEY-----\r?\n?$/;

export const AB7K_APPROVAL_FIELDS=Object.freeze(["domain","version","type","environment",
 "keyId","signerRole","signerId","ownerId","teamLeaderId","subjectId",
 "digest","targetHash","nonce","issuedAtMs","expiresAtMs"]);

const isObject=x=>x!==null&&typeof x==="object"&&!Array.isArray(x);
const exactKeys=(v,keys)=>isObject(v)&&Object.keys(v).sort().join("|")===[...keys].sort().join("|");
const posInt=x=>Number.isSafeInteger(x)&&x>0;
const FIELD_OK=Object.freeze({
 domain:v=>v===AB7K_APPROVAL_DOMAIN,
 version:v=>v===AB7K_APPROVAL_VERSION,
 type:v=>AB7K_APPROVAL_TYPES.includes(v),
 environment:v=>v==="staging",
 keyId:v=>typeof v==="string"&&KEY_ID.test(v),
 signerRole:v=>AB7K_SIGNER_ROLES.includes(v),
 signerId:v=>typeof v==="string"&&UUID.test(v),
 ownerId:v=>typeof v==="string"&&UUID.test(v),
 teamLeaderId:v=>typeof v==="string"&&UUID.test(v),
 subjectId:v=>typeof v==="string"&&UUID.test(v),
 digest:v=>typeof v==="string"&&HEX64.test(v),
 targetHash:v=>typeof v==="string"&&HEX64.test(v),
 nonce:v=>typeof v==="string"&&UUID.test(v),
 issuedAtMs:posInt,
 expiresAtMs:posInt,
});
const deny=reason=>Object.freeze({ok:false,reason,signatureVerified:false,
 approved:false,canAuthorize:false});

/** Canonical signed bytes, or null if any field is missing/extra/malformed.
 * Fixed field order, `key=value\n` lines, strictly validated values (none can
 * contain a newline or `=` ambiguity), preceded by a domain/version header.
 */
export function canonicalAb7kApprovalBytes(payload){
 if(!exactKeys(payload,AB7K_APPROVAL_FIELDS))return null;
 for(const k of AB7K_APPROVAL_FIELDS)if(!FIELD_OK[k](payload[k]))return null;
 const body=AB7K_APPROVAL_FIELDS.map(k=>`${k}=${payload[k]}\n`).join("");
 return Buffer.from(`${AB7K_APPROVAL_DOMAIN}/${AB7K_APPROVAL_VERSION}\n${body}`,"utf8");
}

/** Deterministic target binding, e.g. over [conversationId,revision,action]. */
export function deriveAb7kTargetHash(label,parts){
 if(typeof label!=="string"||!/^[A-Z0-9_]{3,40}$/.test(label)||
    !Array.isArray(parts)||parts.length<1||parts.length>16)return null;
 const items=[];
 for(const p of parts){
  const s=typeof p==="number"&&Number.isSafeInteger(p)?String(p):p;
  if(typeof s!=="string"||s.length<1||s.length>128||/[\r\n]/.test(s))return null;
  items.push(s);
 }
 return createHash("sha256")
  .update(`${AB7K_APPROVAL_DOMAIN}/${AB7K_APPROVAL_VERSION}/target/${label}\n${items.join("\n")}`,"utf8")
  .digest("hex");
}

function spkiFingerprint(key){
 return createHash("sha256").update(key.export({format:"der",type:"spki"})).digest("hex");
}

const REGISTRY_ENTRY_KEYS=["keyId","publicKeyPem","publicKeyFingerprint",
 "signerId","signerRole","notBeforeMs","notAfterMs"];

/** Validate a pinned signer registry. Returns Map(keyId -> entry) or null.
 * Any invalid entry invalidates the WHOLE registry (fail closed). Private-key
 * PEMs are rejected: createPublicKey() would silently derive a public key.
 */
export function normalizeAb7kSignerRegistry(raw){
 if(!Array.isArray(raw)||raw.length<1||raw.length>MAX_REGISTRY_ENTRIES)return null;
 const byKeyId=new Map(),fingerprints=new Set(),roleBySigner=new Map();
 for(const r of raw){
  if(!exactKeys(r,REGISTRY_ENTRY_KEYS)||typeof r.keyId!=="string"||!KEY_ID.test(r.keyId)||
     typeof r.signerId!=="string"||!UUID.test(r.signerId)||
     !AB7K_SIGNER_ROLES.includes(r.signerRole)||
     !posInt(r.notBeforeMs)||!posInt(r.notAfterMs)||r.notAfterMs<=r.notBeforeMs||
     typeof r.publicKeyFingerprint!=="string"||!HEX64.test(r.publicKeyFingerprint)||
     typeof r.publicKeyPem!=="string"||r.publicKeyPem.length>1024||
     /PRIVATE/i.test(r.publicKeyPem)||!PUBLIC_PEM.test(r.publicKeyPem))return null;
  let key;
  try{
   key=createPublicKey(r.publicKeyPem);
   if(key.type!=="public"||key.asymmetricKeyType!=="ed25519")return null;
   if(spkiFingerprint(key)!==r.publicKeyFingerprint)return null;
  }catch{return null;}
  // One signer, one role: an identity that is both Owner and TL voids independence.
  if(byKeyId.has(r.keyId)||fingerprints.has(r.publicKeyFingerprint)||
     (roleBySigner.has(r.signerId)&&roleBySigner.get(r.signerId)!==r.signerRole))return null;
  byKeyId.set(r.keyId,Object.freeze({...r,key}));
  fingerprints.add(r.publicKeyFingerprint);roleBySigner.set(r.signerId,r.signerRole);
 }
 return byKeyId;
}

/** Reads the PUBLIC pinned registry from env. Missing/empty/invalid => null (DENY). */
export function loadAb7kSignerRegistryFromEnv(env=process.env){
 const text=env?.[AB7K_SIGNER_REGISTRY_ENV];
 if(typeof text!=="string"||text.trim()===""||text.length>16384)return null;
 try{return normalizeAb7kSignerRegistry(JSON.parse(text));}catch{return null;}
}

function expectedOk(e){
 return isObject(e)&&AB7K_APPROVAL_TYPES.includes(e.type)&&
  ["subjectId","ownerId","teamLeaderId"].every(k=>typeof e[k]==="string"&&UUID.test(e[k]))&&
  ["digest","targetHash"].every(k=>typeof e[k]==="string"&&HEX64.test(e[k]))&&
  e.ownerId!==e.teamLeaderId;
}

/** Everything except replay claiming. Returns {ok:true,payload,entry} or a deny. */
function verifyOne({envelope,registry,expected,signerRole,now}){
 if(!exactKeys(envelope,["payload","signature"]))return deny("ENVELOPE_SHAPE_DENIED");
 const bytes=canonicalAb7kApprovalBytes(envelope.payload);
 if(!bytes)return deny("PAYLOAD_SHAPE_DENIED");
 const p=envelope.payload;
 if(p.type!==expected.type||p.subjectId!==expected.subjectId||
    p.digest!==expected.digest||p.targetHash!==expected.targetHash||
    p.ownerId!==expected.ownerId||p.teamLeaderId!==expected.teamLeaderId)
  return deny("SUBJECT_BINDING_DENIED");
 if(p.ownerId===p.teamLeaderId)return deny("INDEPENDENCE_DENIED");
 if(p.signerRole!==signerRole||
    p.signerId!==(signerRole==="OWNER"?p.ownerId:p.teamLeaderId))
  return deny("SIGNER_ROLE_OR_SUBJECT_DENIED");
 if(p.issuedAtMs>now+MAX_SKEW_MS)return deny("NOT_YET_VALID");
 if(p.expiresAtMs<=now)return deny("EXPIRED");
 if(now-p.issuedAtMs>AB7K_MAX_LIFETIME_MS||
    p.expiresAtMs-p.issuedAtMs>AB7K_MAX_LIFETIME_MS||p.expiresAtMs<=p.issuedAtMs)
  return deny("LIFETIME_DENIED");
 const entry=registry.get(p.keyId);
 if(!entry)return deny("UNKNOWN_KEY_ID");
 if(entry.signerId!==p.signerId||entry.signerRole!==p.signerRole)
  return deny("KEY_NOT_ENROLLED_FOR_SIGNER_ROLE");
 if(now<entry.notBeforeMs||now>=entry.notAfterMs)return deny("KEY_OUTSIDE_VALIDITY_WINDOW");
 if(typeof envelope.signature!=="string"||!SIGNATURE.test(envelope.signature))
  return deny("SIGNATURE_ENCODING_DENIED");
 const sig=Buffer.from(envelope.signature,"base64url");
 // Reject non-canonical base64url so one signature has exactly one encoding.
 if(sig.length!==64||sig.toString("base64url")!==envelope.signature)
  return deny("SIGNATURE_ENCODING_DENIED");
 let good=false;
 try{good=verify(null,bytes,entry.key,sig)===true;}catch{good=false;}
 if(!good)return deny("SIGNATURE_INVALID");
 return {ok:true,payload:p,entry};
}

function replayKey(p){
 return createHash("sha256")
  .update(`${AB7K_APPROVAL_DOMAIN}/${AB7K_APPROVAL_VERSION}/nonce|${p.type}|${p.nonce}`,"utf8")
  .digest("hex");
}
async function claim(store,p){
 try{return (await store.claim(replayKey(p)))===true;}catch{return false;}
}
const storeOk=s=>isObject(s)&&typeof s.claim==="function";
const nowOk=n=>Number.isSafeInteger(n)&&n>0;

const REQUIRES=Object.freeze(["REAL_ENROLLED_HUMAN_SIGNER_PROVENANCE",
 "SERVER_VERIFIED_CURRENT_AAL2_OWNER_AND_TL","AUTHORIZED_ATOMIC_DB_WRITER_REVALIDATING_ALL",
 "INDEPENDENT_DBA_APPSEC_REVIEW"]);
const success=(extra)=>Object.freeze({ok:true,signatureVerified:true,replayClaimed:true,
 approved:false,canAuthorize:false,requires:REQUIRES,...extra});

/** Verify ONE signer's envelope (Owner or Team Leader) and claim its nonce. */
export async function verifyAb7kSignedApproval({envelope,registry,expected,signerRole,
 replayStore,now=Date.now()}={}){
 const reg=normalizeAb7kSignerRegistry(registry instanceof Map?[...registry.values()]
  .map(({key,...rest})=>rest):registry);
 if(!reg)return deny("SIGNER_REGISTRY_UNCONFIGURED_DENY");
 if(!expectedOk(expected)||!AB7K_SIGNER_ROLES.includes(signerRole)||!nowOk(now))
  return deny("EXPECTED_SUBJECT_INVALID");
 if(!storeOk(replayStore))return deny("REPLAY_STORE_REQUIRED");
 const v=verifyOne({envelope,registry:reg,expected,signerRole,now});
 if(!v.ok)return v;
 if(!(await claim(replayStore,v.payload)))return deny("REPLAY_OR_STORE_DENIED");
 return success({signerRole,signerId:v.payload.signerId,keyId:v.payload.keyId,
  nonce:v.payload.nonce,replayStoreDurable:replayStore.durable===true});
}

/** Verify the independent Owner + Team Leader pair for one subject. Nothing is
 * claimed unless BOTH signatures verify; then both nonces are claimed.
 */
export async function verifyAb7kIndependentApprovalPair({ownerEnvelope,teamLeaderEnvelope,
 registry,expected,replayStore,now=Date.now()}={}){
 const reg=normalizeAb7kSignerRegistry(registry instanceof Map?[...registry.values()]
  .map(({key,...rest})=>rest):registry);
 if(!reg)return deny("SIGNER_REGISTRY_UNCONFIGURED_DENY");
 if(!expectedOk(expected)||!nowOk(now))return deny("EXPECTED_SUBJECT_INVALID");
 if(!storeOk(replayStore))return deny("REPLAY_STORE_REQUIRED");
 const o=verifyOne({envelope:ownerEnvelope,registry:reg,expected,signerRole:"OWNER",now});
 if(!o.ok)return o;
 const t=verifyOne({envelope:teamLeaderEnvelope,registry:reg,expected,signerRole:"TEAM_LEADER",now});
 if(!t.ok)return t;
 if(o.payload.signerId===t.payload.signerId||o.payload.keyId===t.payload.keyId||
    o.payload.nonce===t.payload.nonce)return deny("INDEPENDENCE_DENIED");
 if(!(await claim(replayStore,o.payload)))return deny("REPLAY_OR_STORE_DENIED");
 if(!(await claim(replayStore,t.payload)))return deny("REPLAY_OR_STORE_DENIED");
 return success({ownerId:o.payload.signerId,teamLeaderId:t.payload.signerId,
  ownerNonce:o.payload.nonce,teamLeaderNonce:t.payload.nonce,
  replayStoreDurable:replayStore.durable===true});
}
