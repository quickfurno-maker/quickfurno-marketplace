ok("default off",c.includes('VOX_OPERATIONAL_PROPOSAL_UI_ENABLED!=="staging"'));
ok("scoped staff mode",c.includes('VOX_STAFF_VIEW_MODE!=="scoped"'));
ok("fresh MFA verification",c.includes("await verifiedMfaSession()"));
