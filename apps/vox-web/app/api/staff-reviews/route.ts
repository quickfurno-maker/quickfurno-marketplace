import {randomUUID} from "node:crypto";
import {allowedOrigin,safeJson} from "../../../lib/auth";
import {fetchTeamLeaderReviewQueue,submitTeamLeaderReview} from "../../../lib/core";
export const runtime="nodejs";export const dynamic="force-dynamic";
const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
export async function GET(){const r=await fetchTeamLeaderReviewQueue();return safeJson(r,r.status);}
export async function POST(request:Request){
 if(!allowedOrigin(request))return safeJson({ok:false,error:"ORIGIN_DENIED"},403);
 if(!request.headers.get("content-type")?.startsWith("application/json"))
  return safeJson({ok:false,error:"INVALID_CONTENT_TYPE"},415);
 try{
  const body=await request.text();
  if(body.length>256)return safeJson({ok:false,error:"PAYLOAD_TOO_LARGE"},413);
  const data:unknown=JSON.parse(body);
  if(!data||typeof data!=="object"||Array.isArray(data))return safeJson({ok:false,error:"INVALID_BODY"},400);
  const x=data as Record<string,unknown>;
  if(typeof x.requestId!=="string"||!UUID.test(x.requestId)||x.expectedRevision!==0||
     (x.decision!=="APPROVE"&&x.decision!=="REJECT"))
   return safeJson({ok:false,error:"INVALID_REVIEW"},400);
  // Internal correlation generated by VOX, not by browser-provided approval actor.
  const result=await submitTeamLeaderReview(x.requestId,x.decision,"VOX-REVIEW-"+randomUUID());
  return safeJson(result,result.status);
 }catch{return safeJson({ok:false,error:"REVIEW_UNAVAILABLE"},503);}
}
export function PATCH(){return safeJson({ok:false,error:"METHOD_NOT_ALLOWED"},405);}
export function DELETE(){return safeJson({ok:false,error:"METHOD_NOT_ALLOWED"},405);}
