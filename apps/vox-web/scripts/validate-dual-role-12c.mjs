import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
const root=resolve(import.meta.dirname,".."),read=p=>readFileSync(resolve(root,p),"utf8");
const c=read("lib/core.ts"),auth=read("lib/auth.ts");
const env=read(".env.example");
let n=0;
const check=(name,pass)=>{assert.ok(pass,name);console.log("PASS "+name);n++};
check("platform remains disabled by default",c.includes('VOX_STAFF_PORTAL_ENABLED!=="staging"'));
check("dual mode is opt-in",c.includes('mode==="dual"?["/api/vox/v1/overview","/api/vox/v1/my-work"]'));
check("owner-only path still available",c.includes('mode==="owner"?["/api/vox/v1/overview"]'));
check("scoped-only path still available",c.includes('mode==="scoped"?["/api/vox/v1/my-work"]'));
check("unknown mode fails closed",c.includes('STAFF_SCOPE_MODE_DISABLED'));
check("MFA before any Core request",c.indexOf("await verifiedMfaSession()")<c.indexOf("const mode=process.env.VOX_STAFF_VIEW_MODE"));
check("owner refused only with 403 triggers scoped lookup",c.includes('candidate.status===403)continue'));
check("fallback only dual owner first",c.includes('mode==="dual"&&path==="/api/vox/v1/overview"'));
check("no owner 500 to scoped fallback",!c.includes('candidate.status>=500)continue'));
check("Core bearer verified separately for each route",c.includes('headers:{authorization:"Bearer "+token'));
check("every Core request no-store",c.includes('cache:"no-store",redirect:"error"'));
check("no successful Core response means denied",c.includes('if(!r)return {ok:false,status:403'));
check("schema filter preserved",c.includes('view?.schema!=="qf.vox.overview.v1"'));
check("no arbitrary owner provider content",c.includes('view.prospectPreview.slice(0,8)'));
check("owner-only operations additionally Core-gated",c.includes('/api/vox/v1/aos-health'));
check("scoped operations additionally Core-gated",c.includes('/api/vox/v1/acquisition')||c.includes('"/api/vox/v1/"+key'));
check("both owner and scoped modes include dual without switching role",c.includes('(process.env.VOX_STAFF_VIEW_MODE!=="owner"&&process.env.VOX_STAFF_VIEW_MODE!=="dual")')&&c.includes('(process.env.VOX_STAFF_VIEW_MODE!=="scoped"&&process.env.VOX_STAFF_VIEW_MODE!=="dual")'));
check("dual mode appears only in locked config",env.includes("VOX_STAFF_VIEW_MODE"));
check("session verified against server provider",auth.includes("getUser")||auth.includes("verifiedMfaSession"));
console.log("VOX12C_DUAL_ROLE_CORE_AUTH_GUARDS_PASS "+n+"/19");
