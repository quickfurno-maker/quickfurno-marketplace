ok("response pending only",c.includes('body.state!=="PENDING"'));
ok("no execution receipt",c.includes('body.execution!=="NOT_AUTHORIZED"'));
ok("same Origin",api.includes("allowedOrigin(request)"));
ok("bounded request",api.includes("raw.length>256"));
ok("allowlisted request properties",api.includes("Object.keys(x).some"));
ok("no free text from browser",!api.includes("x.rationale"));
